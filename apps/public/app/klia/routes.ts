export function kliaRoute(name: string, params: Record<string, string | number> | (string | number)[] = {}): string {
    const path = KLIA_ROUTES[name]
    if (!path) return '/'
    const list = Array.isArray(params) ? [...params] : null
    return path.replace(/\{([a-zA-Z_]+)(?::[a-z_]+)?\}/g, (_, key) => String(list ? (list.shift() ?? '') : (params as Record<string, string | number>)[key] ?? ''))
}
